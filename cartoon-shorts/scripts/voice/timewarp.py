#!/usr/bin/env python3
"""Re-voice a finished short without re-timing it by hand: a smooth time map between the timeline the picture and
sound were authored on (old narration) and a new narration of the same text.

The map g(new frame) -> old frame is solved per frame as a bounded least-squares problem: the story's word cues land
on their words (within a frame or two), playback speed stays within [MIN_RATE, MAX_RATE] and changes slowly, and the
end of the voice plus the original tail fills the new length. Needs numpy + scipy (the project's .venv).

  .venv/bin/python scripts/voice/timewarp.py <old words.json> <new words.json> <old total frames> <out.json> <out.ts> [cue frames ...]

out.json  {fps, oldTotal, newTotal, old: [g(0), g(1), ... g(newTotal)]}   (old frame for every new frame)
out.ts    NEW_TOTAL and oldFrame(f) for the composition (generated file, do not edit)
"""

from __future__ import annotations

import json
import sys

sys.dont_write_bytecode = True
import numpy as np  # noqa: E402
from scipy.optimize import lsq_linear  # noqa: E402
from scipy.sparse import lil_matrix  # noqa: E402

FPS = 30
MIN_RATE, MAX_RATE = 0.82, 1.22  # picture plays at most ~18 % slower / 22 % faster than authored
SMOOTH = 60.0                     # weight of speed changes between neighbouring frames
CUE_W, LINE_W, END_W = 3.0, 1.0, 20.0


def main() -> None:
    old_w, new_w = json.load(open(sys.argv[1])), json.load(open(sys.argv[2]))
    old_total = int(sys.argv[3])
    out_json, out_ts = sys.argv[4], sys.argv[5]
    cues = [int(c) for c in sys.argv[6:]]
    if [w["w"] for w in old_w] != [w["w"] for w in new_w]:
        raise SystemExit("the two narrations must have the same words")
    targets: list[tuple[float, float, float, str]] = []  # (new frame, old frame, weight, label)
    for i, w in enumerate(old_w):
        if i == 0 or old_w[i - 1]["line"] != w["line"]:
            targets.append((new_w[i]["s"] * FPS, w["s"] * FPS, LINE_W, f"line {w['line']}"))
    for c in cues:
        i = min(range(len(old_w)), key=lambda k: abs(old_w[k]["s"] * FPS - c))
        if abs(old_w[i]["s"] * FPS - c) <= 2:
            targets.append((new_w[i]["s"] * FPS, float(c), CUE_W, f"cue {c} '{old_w[i]['w']}'"))
        else:
            print(f"warning: cue {c} is not on a word onset, left to the smooth map")
    tail = old_total - old_w[-1]["e"] * FPS
    new_total = int(round(new_w[-1]["e"] * FPS + tail))
    targets.append((new_w[-1]["e"] * FPS, old_w[-1]["e"] * FPS, CUE_W, "voice end"))

    # unknowns: d[k] = g(k+1) - g(k), k = 0..N-1, g(0) = 0
    n = new_total
    rows = len(targets) + (n - 1) + 1
    A = lil_matrix((rows, n))
    b = np.zeros(rows)
    r = 0
    for x, y, wgt, _ in targets:  # g(x) ~ sum_{k < x} d[k] (fractional x: partial last step)
        k = int(np.floor(x))
        A[r, :k] = wgt
        if k < n:
            A[r, k] = wgt * (x - k)
        b[r] = wgt * y
        r += 1
    for k in range(n - 1):
        A[r, k], A[r, k + 1] = -SMOOTH, SMOOTH
        r += 1
    A[r, :] = END_W
    b[r] = END_W * old_total
    res = lsq_linear(A.tocsr(), b, bounds=(MIN_RATE, MAX_RATE), lsmr_tol="auto", max_iter=4000)
    d = res.x
    g = np.concatenate([[0.0], np.cumsum(d)])
    errs = []
    for x, y, _, label in targets:
        gx = np.interp(x, np.arange(n + 1), g)
        errs.append((abs(gx - y), label))
    errs.sort(reverse=True)
    json.dump({"fps": FPS, "oldTotal": old_total, "newTotal": new_total, "old": [round(v, 4) for v in g]}, open(out_json, "w"))
    vals = ",".join(f"{v:.3f}".rstrip("0").rstrip(".") for v in g)
    open(out_ts, "w").write(
        "// GENERATED by scripts/voice/timewarp.py: for every frame of the re-voiced video, the frame of the timeline the story\n"
        "// was authored on (first narration). Do not edit; re-run the script after changing the narration.\n"
        f"export const NEW_TOTAL = {new_total};\n"
        f"const G = [{vals}];\n"
        "export const oldFrame = (f: number): number => {\n"
        "  const i = Math.max(0, Math.min(G.length - 2, Math.floor(f)));\n"
        "  return G[i] + (G[i + 1] - G[i]) * (f - i);\n"
        "};\n")
    print(f"new total {new_total} frames ({new_total / FPS:.2f} s), old {old_total}; solver: {res.message}")
    print(f"speed: min x{d.min():.3f} max x{d.max():.3f}; largest frame-to-frame change {np.abs(np.diff(d)).max():.4f}")
    print("largest cue errors (frames):", ", ".join(f"{e:.1f} ({lab})" for e, lab in errs[:6]))
    print(f"cues within 2 frames: {sum(e <= 2 for e, _ in errs)}/{len(errs)}")


if __name__ == "__main__":
    main()
