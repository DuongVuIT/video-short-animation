#!/usr/bin/env python3
"""Frame tables of a narration for a long episode: reads <voice dir>/words.json + lines.json (scripts/voice/voice_local.py)
and writes <out.ts> with LN (first/last frame of every line), WD (onset frame of every word, per line), WE (end frame of
every word) and VOICE_END. usage: python3 scripts/voice/timing_ts.py shorts/<ep>/voice src/videos/<ep>/timing.ts [fps=30]"""
import json, sys
from pathlib import Path
v, out = Path(sys.argv[1]), Path(sys.argv[2]); fps = float(sys.argv[3]) if len(sys.argv) > 3 else 30
words = json.load(open(v / "words.json")); lines = json.load(open(v / "lines.json"))
n = len(lines); wd = [[] for _ in range(n)]; we = [[] for _ in range(n)]
for w in words:
    wd[w["line"] - 1].append(round(w["s"] * fps)); we[w["line"] - 1].append(round(w["e"] * fps))
ln = [[round(l["s"] * fps), round(l["e"] * fps)] for l in lines]
txt = "// generated by scripts/voice/timing_ts.py from the narration (do not edit): frames at %g fps\n" % fps
txt += "/** [first frame, last frame] of narration line i (0-based) */\nexport const LN: [number, number][] = %s;\n" % json.dumps(ln)
txt += "/** onset frame of every word of line i */\nexport const WD: number[][] = %s;\n" % json.dumps(wd)
txt += "/** end frame of every word of line i */\nexport const WE: number[][] = %s;\n" % json.dumps(we)
txt += "export const VOICE_END = %d;\n" % max(l[1] for l in ln)
txt += "/* lines:\n" + "\n".join("%2d %5d-%5d %s" % (i + 1, ln[i][0], ln[i][1], lines[i]["text"]) for i in range(n)) + "\n*/\n"
out.write_text(txt); print(out, n, "lines", sum(map(len, wd)), "words", "voice ends at frame", max(l[1] for l in ln))
