#!/usr/bin/env python3
"""Write src/engine/API.md: every export of the shared engine with its signature and the first line of its comment.

A new episode is written against this index instead of re-reading the engine sources (about 6000 lines).
Run it after changing anything in src/engine/:   python3 scripts/engine_index.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "src" / "engine"
ORDER = ["toon", "paint", "build", "lights", "grade", "shade", "cardshade", "ink", "lensblur"]
EXPORT = re.compile(r"^export (?:declare )?(const|let|function|class|type|interface|enum) ([A-Za-z_$][\w$]*)")
MAX_SIG = 190


def signature(line: str, kind: str) -> str:
    """the declaration up to its body: parameters and types stay, implementations go"""
    s = line.strip()
    s = re.sub(r"^export ", "", s)
    if kind in ("type", "interface"):
        return s if len(s) <= MAX_SIG else s[:MAX_SIG].rstrip() + " ..."
    arrow = s.find("=> {")
    if arrow < 0:
        arrow = s.find("=>")
    if kind == "const" and arrow > 0:
        s = s[:arrow].rstrip()
    elif kind in ("function", "class"):
        s = s.split("{")[0].rstrip()
    elif kind in ("const", "let"):
        m = re.match(r"((?:const|let) [\w$]+(?:\s*:\s*[^=]+?)?)\s*=", s)
        s = m.group(1) if m else s
    return s if len(s) <= MAX_SIG else s[:MAX_SIG].rstrip() + " ..."


def type_body(lines: list[str], i: int, limit: int = 60) -> list[str] | None:
    """the whole declaration of a type / interface that runs over several lines (None for a one-liner)"""
    depth = 0
    for j in range(i, min(len(lines), i + limit)):
        code = lines[j].split("//")[0]
        depth += code.count("{") + code.count("(") - code.count("}") - code.count(")")
        nxt = lines[j + 1].lstrip() if j + 1 < len(lines) else ""
        if depth <= 0 and not nxt.startswith("|") and (code.rstrip().endswith((";", "}")) or j > i):
            return None if j == i else [re.sub(r"^export ", "", ln) for ln in lines[i:j + 1]]
    return None


def doc_above(lines: list[str], i: int) -> str:
    """first sentence of the // or /** */ comment right above line i"""
    j = i - 1
    block: list[str] = []
    while j >= 0 and (lines[j].lstrip().startswith(("//", "*", "/**")) or lines[j].strip().endswith("*/")):
        block.insert(0, lines[j])
        if lines[j].lstrip().startswith("/**"):
            break
        j -= 1
    if j < 0:
        return ""  # the file's header comment, already printed under the file name
    text = " ".join(re.sub(r"^\s*(/\*\*|\*/|\*|//)\s?", "", b).replace("*/", "").strip() for b in block).strip()
    if text.startswith("-----"):
        return ""
    return text if len(text) <= 230 else text[:230].rstrip() + " ..."


def main() -> None:
    files = [ENGINE / f"{n}.ts" for n in ORDER if (ENGINE / f"{n}.ts").exists()]
    files += sorted(p for p in ENGINE.glob("*.ts") if p not in files)
    out = ["# Engine API (generated by scripts/engine_index.py; do not edit by hand)", ""]
    total = 0
    for p in files:
        lines = p.read_text(encoding="utf-8").split("\n")
        head = []
        for ln in lines:
            if not ln.startswith("//"):
                break
            head.append(ln[2:].strip())
        out += [f"## {p.name} ({len(lines)} lines)", ""]
        if head:
            out += [" ".join(head), ""]
        section = ""
        for i, ln in enumerate(lines):
            sec = re.match(r"^// -{4,} (.+?) -{4,}", ln)
            if sec:
                section = sec.group(1)
                continue
            m = EXPORT.match(ln)
            if not m:
                continue
            if section:
                out += [f"**{section}**", ""]
                section = ""
            doc = doc_above(lines, i)
            total += 1
            body = type_body(lines, i) if m.group(1) in ("type", "interface") else None
            if body:  # option bags and unions are the API: print them whole
                out += [f"- `{m.group(1)} {m.group(2)}` (line {i + 1})" + (f": {doc}" if doc else ""), "", "```ts", *body, "```", ""]
                continue
            out.append(f"- `{signature(ln, m.group(1))}` (line {i + 1})" + (f": {doc}" if doc else ""))
        out.append("")
    (ENGINE / "API.md").write_text("\n".join(out), encoding="utf-8")
    print(f"src/engine/API.md: {total} exports from {len(files)} files")


if __name__ == "__main__":
    main()
